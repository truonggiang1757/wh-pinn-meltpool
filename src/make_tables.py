def G(exp, case, group, df=D):
    return df[(df.exp == exp) & (df.case == case) & (df.group == group)]


def ms(key, col, df=D):
    s = G(*key, df=df)[col].dropna()
    return float(s.mean()), (float(s.std()) if len(s) > 1 else 0.0), int(len(s))


def pw(k1, k2, col):
    a, b = G(*k1)[col].dropna(), G(*k2)[col].dropna()
    return float(ttest_ind(a, b, equal_var=False).pvalue) if len(a) > 1 and len(b) > 1 else float('nan')


def pm(t, nd, sd_nd=None):
    return f'{t[0]:.{nd}f} ± {t[1]:.{nd if sd_nd is None else sd_nd}f}'


def table(title, header, rows, note=''):
    out = [f'### {title}', '', '| ' + ' | '.join(header) + ' |', '|' + '---|' * len(header)]
    out += ['| ' + ' | '.join(str(c) for c in r) + ' |' for r in rows]
    return '\n'.join(out + ([f'', note] if note else []) + ['', ''])


