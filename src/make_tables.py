def of_cos(c):
    P, z = ptv[c], ofm[c]
    a, b, u, v = P['vx_filt_ms'], P['vy_filt_ms'], z['u_ms'], z['v_ms']
    ok = (np.hypot(a, b) > 1e-4) & (np.hypot(u, v) > 1e-6)
    return float(np.median(np.clip((a * u + b * v)[ok] / (np.hypot(a, b) * np.hypot(u, v))[ok], -1, 1)))


